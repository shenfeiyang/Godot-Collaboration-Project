def set_font(run, size=10.5, bold=False, color=None):
    run.font.name = '宋体'
    run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = RGBColor.from_string(color)

def shade_cell(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:fill'), fill)
    tcPr.append(shd)

def p(doc, text='', style=None, size=10.5, bold=False, color=None):
    para = doc.add_paragraph(style=style)
    para.paragraph_format.line_spacing = 1.25
    run = para.add_run(text)
    set_font(run, size=size, bold=bold, color=color)
    return para

def bullet(doc, items):
    for item in items:
        para = doc.add_paragraph(style='List Bullet')
        para.paragraph_format.line_spacing = 1.18
        run = para.add_run(item)
        set_font(run)

def reply_box(doc, label='你的回复 / 修改意见：'):
    p(doc, label, bold=True, color='C00000')
    t = doc.add_table(rows=1, cols=1)
    t.style = 'Table Grid'
    cell = t.rows[0].cells[0]
    cell.text = '\n\n\n'
    shade_cell(cell, 'FFF2CC')
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.TOP

def q(doc, text):
    p(doc, text, bold=True)
    reply_box(doc)

def section(doc, title, questions):
    doc.add_heading(title, level=2)
    for item in questions:
        q(doc, item)

